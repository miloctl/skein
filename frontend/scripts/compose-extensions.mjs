import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const raw = process.env.SKEIN_FRONTEND_EXTENSIONS ?? "";
const modules = raw
  .split(",")
  .map((value) => value.trim())
  .filter(Boolean);
const safe = /^[@A-Za-z0-9_.\/-]+$/;
for (const moduleName of modules) {
  if (!safe.test(moduleName) || moduleName.startsWith("/")) {
    throw new Error(`Invalid frontend extension module: ${moduleName}`);
  }
}
const imports = modules.map(
  (moduleName, index) => `import extension${index} from ${JSON.stringify(moduleName)};`,
);
const values = modules.map((_moduleName, index) => `extension${index}`);
const source = `// Generated by scripts/compose-extensions.mjs. Do not edit.\n\
import type { FrontendExtension } from "@/lib/extensions/contracts";\n\
${imports.join("\n")}\n\
export const compiledExtensions: readonly FrontendExtension[] = [${values.join(", ")}];\n`;
const target = fileURLToPath(new URL("../extensions/generated.ts", import.meta.url));
writeFileSync(target, source);

// Tailwind scans no installed package on its own, so a utility used only by
// an extension was silently absent from the production CSS. Each allowlisted
// package becomes an @source the build scans.
const sources = modules.map(
  (moduleName) => `@source ${JSON.stringify(`../node_modules/${moduleName}`)};`,
);
const cssTarget = fileURLToPath(
  new URL("../extensions/generated-sources.css", import.meta.url),
);
writeFileSync(
  cssTarget,
  `/* Generated by scripts/compose-extensions.mjs. Do not edit. */\n${sources.join("\n")}\n`,
);
console.log(`Composed ${modules.length} frontend extension module(s).`);
