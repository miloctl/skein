import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const hostRoot = fileURLToPath(new URL("..", import.meta.url));
const workspaceRoot = realpathSync(
  process.env.SKEIN_FRONTEND_WORKSPACE_ROOT ?? hostRoot,
);
const requireFromWorkspace = createRequire(path.join(workspaceRoot, "package.json"));
const packageName = /^(?:@[A-Za-z0-9][A-Za-z0-9._-]*\/)?[A-Za-z0-9][A-Za-z0-9._-]*$/;
const raw = process.env.SKEIN_FRONTEND_EXTENSIONS ?? "";
const modules = raw
  .split(",")
  .map((value) => value.trim())
  .filter(Boolean);

for (const moduleName of modules) {
  if (!packageName.test(moduleName)) {
    throw new Error("A frontend extension package name is invalid. Use an npm package name.");
  }
}
if (new Set(modules).size !== modules.length) {
  throw new Error("A frontend extension package occurs more than once. Remove the duplicate package.");
}

function packageRoot(name) {
  for (const modulesDir of requireFromWorkspace.resolve.paths(name) ?? []) {
    const current = path.join(modulesDir, name);
    try {
      if (JSON.parse(readFileSync(path.join(current, "package.json"), "utf8")).name === name) {
        const root = realpathSync(current);
        const relative = path.relative(workspaceRoot, root);
        if (relative.startsWith("..") || path.isAbsolute(relative)) {
          throw new Error(
            "A frontend extension package resolves outside the workplace root. Install it inside the workplace root.",
          );
        }
        return root;
      }
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
  }
  throw new Error(
    "A frontend extension package is not installed. Add it to the workplace dependencies.",
  );
}

const imports = modules.map(
  (moduleName, index) => `import extension${index} from ${JSON.stringify(moduleName)};`,
);
const values = modules.map((_moduleName, index) => `extension${index}`);
const source = `// Generated by scripts/compose-extensions.mjs. Do not edit.\n\
import type { FrontendExtension } from "@/lib/extensions/contracts";\n\
${imports.join("\n")}\n\
export const compiledExtensions: readonly FrontendExtension[] = [${values.join(", ")}];\n`;
const extensionsDir = fileURLToPath(new URL("../extensions", import.meta.url));
mkdirSync(extensionsDir, { recursive: true });
writeFileSync(path.join(extensionsDir, "generated.ts"), source);

// Tailwind scans no installed package on its own. The API contains shared
// component classes, and every explicit extension contributes its compiled
// package directory.
const roots = [packageRoot("@skein/extension-api"), ...modules.map(packageRoot)];
const sources = roots.map((root) => {
  const relative = path.relative(extensionsDir, root).split(path.sep).join("/");
  return `@source ${JSON.stringify(relative)};`;
});
writeFileSync(
  path.join(extensionsDir, "generated-sources.css"),
  `/* Generated by scripts/compose-extensions.mjs. Do not edit. */\n${sources.join("\n")}\n`,
);
const count = modules.length;
console.log(`Composed ${count} frontend extension ${count === 1 ? "module" : "modules"}.`);
